gauge_data = json.loads(Path("gauge_holonomy_results.json").read_text())

p = 2
core_complement_generator = 1
core_meridian = p * core_complement_generator


def character(phase, integer):
    return cmath.exp(1j * phase * integer)


ambient_torsion_phase = math.pi
ambient_on_generator = character(ambient_torsion_phase, core_complement_generator)
ambient_on_meridian = character(ambient_torsion_phase, core_meridian)

square_root_phases = [math.pi / 2.0, -math.pi / 2.0]
square_root_branches = []
for phase in square_root_phases:
    on_generator = character(phase, core_complement_generator)
    on_meridian = character(phase, core_meridian)
    square_root_branches.append(
        {
            "phase_on_generator_over_pi": phase / math.pi,
            "holonomy_on_generator": [on_generator.real, on_generator.imag],
            "square_on_generator": [
                (on_generator**2).real,
                (on_generator**2).imag,
            ],
            "holonomy_on_core_meridian": [on_meridian.real, on_meridian.imag],
            "descends_across_core": abs(on_meridian - 1.0) < 1e-12,
        }
    )

quarter_branch = next(
    row for row in gauge_data["beta_sweep"] if abs(row["beta"] - 0.25) < 1e-12
)
gauge_holonomies = [
    cmath.exp(1j * math.pi * quarter_branch["theta_plus_over_pi"]),
    cmath.exp(1j * math.pi * quarter_branch["theta_minus_over_pi"]),
]

