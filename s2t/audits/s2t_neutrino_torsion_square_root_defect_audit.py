majorana_pair_charge = 2
forced_pair_phase_change = majorana_pair_charge * meridian_fermion_phase
forced_vortex_winding = int(round(forced_pair_phase_change / (2.0 * math.pi)))
forced_mod2_index = forced_vortex_winding % 2

spin_holonomy_on_core = -1
ambient_torsion_holonomy_on_core = -1
candidate_core_holonomy = spin_holonomy_on_core * ambient_torsion_holonomy_on_core

